#!/usr/bin/env python3
"""Generate Surge PT DNS files from domains.json. No network or secret access."""
import argparse
import json
import re
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parents[1]
HEADER = '#!name=PT DNS - Domestic default / JP-HK exceptions\n#!desc=Unlisted domains keep domestic encrypted DNS; listed exceptions use Cloudflare via the main-profile DNS policy. No GeoIP claim is made.\n#!author=qingzhh\n#!homepage=https://github.com/qingzhh/public-resources/tree/main/network/surge\n#!category=qingzhh\n\n# 2026-10-12 revision 2. Generated by scripts/build_pt_dns.py.\n# Edit network/pt-dns/domains.json, NOT this generated file.\n# The original 34 exceptions are preserved, not proven to be 34 poisoned names.\n# No current A/AAAA geolocation or user-line connectivity measurement is available.\n# Main profile prerequisites:\n# encrypted-dns-follow-outbound-mode = true\n# DOMAIN,cloudflare-dns.com,DNS-境外\n# Create the policy in [Proxy Group], not inside a module.\n# Native encrypted DNS may fall back to DIRECT when the proxy server uses a\n# hostname. Choose a working IP-address-based proxy and check the traffic log.\n# DNS route and website/Tracker route are independent. Keep the existing rules.\n# No scripts run on the DNS hot path; no static target IPs or credentials.\n# To restore a listed domain to domestic dual DoH without deleting its route,\n# set that entry\'s optional resolver field to "default" and regenerate.\n\n[Host]\n'

def validate_resolver(value: str) -> str:
    """Reject malformed endpoints, credentials and inline-rule injection."""
    if not isinstance(value, str):
        raise ValueError("Resolver must be a string")
    try:
        url = urlparse(value)
        port = url.port
    except ValueError as exc:
        raise ValueError("Invalid resolver URL") from exc
    if (url.scheme != "https" or not url.hostname or url.username or url.password
            or url.query or url.fragment
            or any(c.isspace() for c in value)
            or any(c in value for c in ",#;\\")
            or (port is not None and not 1 <= port <= 65535)):
        raise ValueError("Use one HTTPS DoH URL without credentials, query, or fragment")
    return value

def outputs() -> dict[str, str]:
    data = json.loads((ROOT / "network/pt-dns/domains.json").read_text(encoding="utf-8"))
    if not isinstance(data, dict) or set(data) != {"resolver", "entries"}:
        raise ValueError("Expected resolver and entries")
    default = validate_resolver(data["resolver"])
    if not isinstance(data["entries"], list) or not data["entries"]:
        raise ValueError("entries must be a nonempty list")
    entries, seen = [], set()
    for entry in data["entries"]:
        if (not isinstance(entry, dict)
                or not {"domain", "scope"} <= set(entry)
                or not set(entry) <= {"domain", "scope", "resolver"}):
            raise ValueError("Expected domain, scope and optional resolver")
        domain, scope = entry["domain"], entry["scope"]
        if (not isinstance(domain, str) or len(domain) > 253
                or "." not in domain or domain != domain.lower()
                or not all(re.fullmatch(r"[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?", x)
                           for x in domain.split("."))):
            raise ValueError(f"Invalid domain: {domain!r}")
        if not isinstance(scope, str) or scope not in {"exact", "suffix"} or domain in seen:
            raise ValueError(f"Duplicate domain or invalid scope: {entry!r}")
        seen.add(domain)
        value = entry.get("resolver", default)
        endpoint = None if value == "default" else validate_resolver(value)
        entries.append((domain, scope, endpoint))
    hosts, rules = [], []
    for domain, scope, endpoint in sorted(entries):
        if endpoint is None:
            hosts.append(f"# {domain}: inherit global domestic encrypted DNS; routing retained.")
        else:
            hosts.append(f"{domain} = server:{endpoint}")
            if scope == "suffix":
                hosts.append(f"*.{domain} = server:{endpoint}")
        rules.append(f"{'DOMAIN-SUFFIX' if scope == 'suffix' else 'DOMAIN'},{domain}")
    return {
        "network/pt-dns/pt-dns.sgmodule": HEADER + "\n".join(hosts) + "\n",
        "network/pt-dns/pt.list": "# Generated from domains.json; no policy names in this rule set.\n" + "\n".join(rules) + "\n",
    }

def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify generated files are current")
    args = parser.parse_args()
    stale = []
    for name, content in outputs().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    if stale:
        raise SystemExit("Regenerate files: " + ", ".join(stale))
    print("PT DNS outputs validated" if args.check else "PT DNS outputs generated")

if __name__ == "__main__":
    main()
